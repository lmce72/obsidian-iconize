import typescript from '@rollup/plugin-typescript';
import { nodeResolve } from '@rollup/plugin-node-resolve';
import commonjs from '@rollup/plugin-commonjs';
import alias from '@rollup/plugin-alias';
import copy from 'rollup-plugin-copy';

const isProd = process.env.BUILD === 'production';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ROLLUP
if you want to view the source visit the plugins github repository
*/
`;

const cmModules = [
  '@codemirror/autocomplete',
  '@codemirror/closebrackets',
  '@codemirror/collab',
  '@codemirror/comment',
  '@codemirror/commands',
  '@codemirror/fold',
  '@codemirror/highlight',
  '@codemirror/gutter',
  '@codemirror/history',
  '@codemirror/language',
  '@codemirror/lint',
  '@codemirror/matchbrackets',
  '@codemirror/search',
  '@codemirror/state',
  '@codemirror/stream-parser',
  '@codemirror/rangeset',
  '@codemirror/panel',
  '@codemirror/matchbrackets',
  '@codemirror/text',
  '@codemirror/tooltip',
  '@codemirror/view',
];

export default {
  input: './src/main.ts',
  output: {
    file: './main.js',
    sourcemap: 'inline',
    sourcemapExcludeSources: isProd,
    format: 'cjs',
    exports: 'default',
    banner,
  },
  external: ['obsidian', ...cmModules],
  plugins: [
    alias({
      entries: {
        '@app': 'src',
        '@lib': 'src/lib',
        // 包的 `browser` 字段指向 CJS 构建，里面会 require('fs')；Obsidian 渲染进程没有
        // Node 集成，顶层 require 会让整个 main.js 加载失败。改用无 Node 依赖的 ESM 构建。
        //
        // The package's `browser` field points at the CJS build, which requires 'fs'.
        // The Obsidian renderer has no Node integration, so that top-level require breaks
        // the whole bundle. Use the Node-free ESM build instead.
        'opentype.js': 'opentype.js/dist/opentype.mjs',
      },
    }),
    typescript({ tsconfig: './tsconfig.build.json' }),
    nodeResolve({ browser: true }),
    commonjs(),
    copy({
      targets: [
        { src: './main.js', dest: './dist' },
        { src: './manifest.json', dest: './dist' },
        { src: './src/styles.css', dest: './dist' },
      ],
      hook: 'writeBundle',
    }),
  ],
  onwarn: (warning) => {
    if (warning.code === 'THIS_IS_UNDEFINED') return;

    console.warn(warning.message);
  },
};
